-- Corrosion Atlas: non-destructive programme name catalogue.
-- Run ONCE in the Supabase SQL Editor before deploying the curator changes.
-- Existing sources.programme values remain unchanged for backwards compatibility.

create table if not exists public.programmes (
    id bigint generated by default as identity primary key,
    display_name text not null,
    full_name text not null default '',
    description text not null default '',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint programmes_display_name_not_blank check (btrim(display_name) <> '')
);

create unique index if not exists programmes_display_name_ci_idx
    on public.programmes (lower(btrim(display_name)));

-- The Worker uses the Supabase service-role secret. Do not grant direct
-- access to anon/authenticated PostgREST clients.
alter table public.programmes enable row level security;
revoke all on table public.programmes from anon, authenticated;
grant select, insert, update on table public.programmes to service_role;
grant usage, select on sequence public.programmes_id_seq to service_role;

