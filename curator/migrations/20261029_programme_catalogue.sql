-- Register abbreviations already used by sources without modifying any
-- existing source or inventing an official full name.
insert into public.programmes (display_name)
select distinct x.display_name
from (
  select btrim(value) as display_name
  from public.sources
  cross join lateral regexp_split_to_table(
    coalesce(programme, ''), '[,;]'
  ) as value
) as x
where x.display_name <> ''
  and lower(x.display_name) <> 'other / independent'
on conflict do nothing;

